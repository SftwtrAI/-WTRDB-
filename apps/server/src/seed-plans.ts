async function seedPlans() {
  try {
    console.log("🌱 Starting Plans seed...");

    console.log(`📦 Upserting ${PLANS_SEED_DATA.length} subscription plans...`);
    for (const plan of PLANS_SEED_DATA) {
      await db.execute(sql`
        INSERT INTO plans (
          id, name, display_name, description,
          monthly_price, yearly_price, razorpay_monthly_price, razorpay_yearly_price,
          max_agents, max_campaigns, max_contacts_per_campaign,
          max_webhooks, max_knowledge_bases, max_flows, max_phone_numbers,
          included_credits, default_llm_model, can_choose_llm, can_purchase_numbers,
          use_system_pool, signup_bonus_credits, credit_rollover_months,
          credit_rollover_cap, max_knowledge_base_size_mb, support_tier,
          features, is_active, created_at, updated_at
        ) VALUES (
          gen_random_uuid(), ${plan.name}, ${plan.displayName}, ${plan.description},
          ${plan.monthlyPrice}, ${plan.yearlyPrice}, ${plan.razorpayMonthlyPrice}, ${plan.razorpayYearlyPrice},
          ${plan.maxAgents}, ${plan.maxCampaigns}, ${plan.maxContactsPerCampaign},
          ${plan.maxWebhooks}, ${plan.maxKnowledgeBases}, ${plan.maxFlows}, ${plan.maxPhoneNumbers},
          ${plan.includedCredits}, ${plan.defaultLlmModel}, ${plan.canChooseLlm}, ${plan.canPurchaseNumbers},
          ${plan.useSystemPool}, ${plan.signupBonusCredits}, ${plan.creditRolloverMonths},
          ${plan.creditRolloverCap}, ${plan.maxKnowledgeBaseSizeMb}, ${plan.supportTier},
          ${JSON.stringify(plan.features)}::jsonb, ${plan.isActive}, NOW(), NOW()
        )
        ON CONFLICT (name) DO UPDATE SET
          display_name = EXCLUDED.display_name,
          description = EXCLUDED.description,
          monthly_price = EXCLUDED.monthly_price,
          yearly_price = EXCLUDED.yearly_price,
          razorpay_monthly_price = EXCLUDED.razorpay_monthly_price,
          razorpay_yearly_price = EXCLUDED.razorpay_yearly_price,
          max_agents = EXCLUDED.max_agents,
          max_campaigns = EXCLUDED.max_campaigns,
          max_contacts_per_campaign = EXCLUDED.max_contacts_per_campaign,
          max_webhooks = EXCLUDED.max_webhooks,
          max_knowledge_bases = EXCLUDED.max_knowledge_bases,
          max_flows = EXCLUDED.max_flows,
          max_phone_numbers = EXCLUDED.max_phone_numbers,
          included_credits = EXCLUDED.included_credits,
          default_llm_model = EXCLUDED.default_llm_model,
          can_choose_llm = EXCLUDED.can_choose_llm,
          can_purchase_numbers = EXCLUDED.can_purchase_numbers,
          use_system_pool = EXCLUDED.use_system_pool,
          signup_bonus_credits = EXCLUDED.signup_bonus_credits,
          credit_rollover_months = EXCLUDED.credit_rollover_months,
          credit_rollover_cap = EXCLUDED.credit_rollover_cap,
          max_knowledge_base_size_mb = EXCLUDED.max_knowledge_base_size_mb,
          support_tier = EXCLUDED.support_tier,
          features = EXCLUDED.features,
          is_active = EXCLUDED.is_active,
          updated_at = NOW()
      `);
    }

    console.log("✅ Successfully seeded Plans!");
    PLANS_SEED_DATA.forEach((p) => {
      console.log(
        `   - ${p.displayName}: ₹${p.razorpayMonthlyPrice}/month, ${p.includedCredits} credits`,
      );
    });
  } catch (error) {
    console.error("❌ Error seeding Plans:", error);
    throw error;
  }
}

